/**
 * ZAKUIKit — standalone build.
 *
 * Produces the framework-free deliverables at the repository root from a
 * single source of truth (the same styles/ + scripts/ + demos/ the Astro site
 * uses):
 *
 *   zak.css / zak.min.css — the ONE library bundle: tokens → base → all
 *      component sheets + utilities, cascade-layered. Contains no documentation styles.
 *   zak.js  / zak.min.js  — the ONE library runtime: self-initialising IIFE
 *      exposing window.ZakUI. Contains no docs chrome.
 *   zak-docs.js           — docs bundle: every component runtime plus the
 *      documentation chrome (sidebar, search, copy, scroll-spy) for the
 *      standalone site. The docs-only stylesheet pair (zak.css + zak-docs.js)
 *      keeps documentation styling entirely out of the library artifacts.
 *   index.html            — the complete documentation site generated by
 *      scripts/gen-site.ts (docs CSS inlined; links ./zak-docs.js).
 *
 * The same library artifacts are mirrored into public/ (Astro serves them
 * as-is), package/dist/ (npm + jsDelivr channel) and zakuikit.mjs (ESM).
 *
 * Run: npm run standalone   (then open index.html, or `npx serve .`)
 */
