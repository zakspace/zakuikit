async function readStyle(file) {
  return readFile(join(stylesDir, file), 'utf8');
}
function layered(source, layer) {
  return layer ? `@layer ${layer} {\n${source.trimEnd()}\n}\n` : `${source}\n`;
}

/* ---------------------------------------------------------------- CSS ---- */
let css =
  `/*! ZAKUIKit v${VERSION} — library zak.css (cascade-layered: tokens + base + components + utilities). Generated by scripts/build-standalone.mjs — do not edit directly. */\n` +
  LAYER_HEADER;
for (const [file, layer] of STYLES) {
  const source = await readStyle(file);
  css += `\n/* ${rule2}\n   ${file}\n   ${rule2} */\n\n${layered(source, layer)}`;
}
const minifiedCss = (await transform(css, { loader: 'css', minify: true })).code;

// Library bundle: repo root + npm/CDN channel + the Astro site's public copy.
await writeFile(join(root, 'zak.css'), css);
await writeFile(join(root, 'zak.min.css'), minifiedCss);
await writeFile(join(root, 'public', 'zak.css'), css);
await mkdir(join(root, 'package', 'dist'), { recursive: true });
await writeFile(join(root, 'package', 'dist', 'zak.css'), css);
await writeFile(join(root, 'package', 'dist', 'zak.min.css'), minifiedCss);

// Per-category granular sheets for `zakuikit/css/*` imports.
const pkgCssDir = join(root, 'package', 'dist', 'css');
await mkdir(pkgCssDir, { recursive: true });
for (const [file, layer] of STYLES) {
  const source = await readStyle(file);
  await writeFile(
    join(pkgCssDir, file),
    `/* ZAKUIKit v${VERSION} — ${file} */\n${LAYER_HEADER}\n${layered(source, layer)}`,
  );
}
console.log(`zak.css — library bundle, ${STYLES.length} layered sheets (${(css.length / 1024).toFixed(1)} kB → ${(minifiedCss.length / 1024).toFixed(1)} kB min)`);

// Docs styles (docs.css only — the standalone shim lives in this script and is
// handed to gen-site through a temp manifest so index.html can inline them).
const docsCss = await readStyle('docs.css');
await writeFile(
  join(root, 'scripts', '.docs-css.json'),
  JSON.stringify({ docs: docsCss, shim: STANDALONE_SHIM }),
);

/* ----------------------------------------------------------------- JS ---- */
const jsTemp = join(root, 'scripts', '.tmp-js');
async function bundleJs(entry, format, minify, fileName, name = 'ZAKUI') {
  await build({
    configFile: false,
    logLevel: 'warn',
    build: {
      copyPublicDir: false,
      emptyOutDir: false,
      outDir: jsTemp,
      minify,
      lib: {
        entry: join(root, 'src', 'scripts', entry),
        name,
        formats: [format],
        fileName: () => fileName,
      },
    },
  });
  const code = await readFile(join(jsTemp, fileName), 'utf8');
  const kind =
    entry === 'zak-ui.ts' ? 'library runtime (window.ZakUI)' : entry === 'main.ts' ? 'docs bundle (runtimes + docs chrome)' : 'ESM entry';
  const banner = `/*! ZAKUIKit v${VERSION} — ${kind}${format.toUpperCase() === 'ES' ? '' : ' IIFE'}${minify ? ' (minified)' : ''}. Generated by scripts/build-standalone.mjs — do not edit directly. */\n`;
  await writeFile(join(root, fileName), banner + code);
  await mkdir(join(root, 'package', 'dist'), { recursive: true });
  await writeFile(join(root, 'package', 'dist', fileName), banner + code);
  return code.length;
}

// Library runtime — one file, no docs chrome (root + package/dist + public).
const libSize = await bundleJs('zak-ui.ts', 'iife', false, 'zak.js');
await bundleJs('zak-ui.ts', 'iife', true, 'zak.min.js');
await bundleJs('library.ts', 'es', false, 'zakuikit.mjs');
const { cp } = await import('node:fs/promises');
await cp(join(root, 'zak.js'), join(root, 'public', 'zak.js'));

// Docs bundle — runtimes + documentation chrome for the standalone site.
const docsSize = await bundleJs('main.ts', 'iife', false, 'zak-docs.js');
await rm(jsTemp, { recursive: true, force: true });
console.log(`zak.js — library IIFE (${(libSize / 1024).toFixed(1)} kB) + minified + ESM; zak-docs.js — docs bundle (${(docsSize / 1024).toFixed(1)} kB)`);

/* --------------------------------------------------------------- HTML ---- */
const tempDir = join(root, 'scripts', '.tmp');
await mkdir(tempDir, { recursive: true });
const genOut = join(tempDir, 'gen-site.mjs');
await esbuild({
  entryPoints: [join(root, 'scripts', 'gen-site.ts')],
  outfile: genOut,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  logLevel: 'warning',
  // Node built-ins are provided at runtime, not bundled.
  external: ['node:fs', 'node:fs/promises', 'node:path', 'node:url'],
});
await import(pathToFileURL(genOut).href); // runs the generator (writes index.html)
await rm(tempDir, { recursive: true, force: true });
await rm(join(root, 'scripts', '.docs-css.json'), { force: true });
console.log('index.html — documentation site written to the repository root');
